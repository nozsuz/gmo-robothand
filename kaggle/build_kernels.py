"""Build self-contained Kaggle script kernels that run evaluation shards in parallel.

Each kernel embeds the repository code as a base64 zip, installs MuJoCo, fetches the
Shadow Hand model from GitHub (pinned commit) and runs scripts/evaluate.py with its own
arguments. Results land in the kernel output as eval_<name>.csv / .md.

    uv run python kaggle/build_kernels.py --user nozomisuzuki
    for d in outputs/kaggle_kernels/*/; do kaggle kernels push -p "$d"; done
    # when finished:
    for s in <slugs>; do kaggle kernels output nozomisuzuki/$s -p outputs/kaggle/$s; done
    uv run python scripts/summarize.py --name speed outputs/kaggle/rh-eval-speed-*/eval_*.csv
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "outputs" / "kaggle_kernels"
MUJOCO_VERSION = "3.15.0"

# Held-out layouts: seeds 200+ (0-99 were used during development).
HELD_OUT = ["--seed-offset", "200", "--seeds", "20"]
SHARDS = {
    "rh-eval-speed-a": ["--name", "speed_a", "--speed", "1", "2"],
    "rh-eval-speed-b": ["--name", "speed_b", "--speed", "3", "4"],
    "rh-eval-noise-a": ["--name", "noise_a", "--noise", "0", "0.001"],
    "rh-eval-noise-b": ["--name", "noise_b", "--noise", "0.002", "0.003"],
    "rh-eval-noise-fast": ["--name", "noise_fast", "--speed", "3", "--noise", "0", "0.001", "0.002", "0.003"],
    "rh-eval-friction-fast": ["--name", "friction_fast", "--speed", "3", "--tip-friction", "0.1", "0.2", "0.3", "0.5", "0.8"],
}

RUNNER = '''"""Generated by kaggle/build_kernels.py -- do not edit by hand."""
import base64, io, os, shutil, subprocess, sys, zipfile

CODE = "{code}"
ARGS = {args}
ROOT = "/kaggle/working/repo"

zipfile.ZipFile(io.BytesIO(base64.b64decode(CODE))).extractall(ROOT)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "mujoco=={mujoco}"], check=True)
env = dict(os.environ, PYTHONPATH=f"{{ROOT}}/src:{{ROOT}}/scripts")
print("cpu_count", os.cpu_count(), flush=True)
subprocess.run([sys.executable, f"{{ROOT}}/scripts/fetch_models.py"], check=True, env=env)
subprocess.run(
    [sys.executable, f"{{ROOT}}/scripts/evaluate.py", *ARGS, "--out-dir", "/kaggle/working"], check=True, env=env
)
shutil.rmtree(ROOT)  # keep the kernel output to the result files
'''


def code_zip() -> str:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for path in [*(REPO / "src").rglob("*.py"), *(REPO / "scripts").glob("*.py")]:
            z.write(path, path.relative_to(REPO).as_posix())
    return base64.b64encode(buf.getvalue()).decode()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--user", required=True, help="Kaggle username")
    args = ap.parse_args()

    code = code_zip()
    for slug, shard_args in SHARDS.items():
        d = OUT / slug
        d.mkdir(parents=True, exist_ok=True)
        (d / "run.py").write_text(
            RUNNER.format(code=code, args=repr(HELD_OUT + shard_args), mujoco=MUJOCO_VERSION), encoding="utf-8"
        )
        meta = {
            "id": f"{args.user}/{slug}",
            "title": slug,
            "code_file": "run.py",
            "language": "python",
            "kernel_type": "script",
            "is_private": True,
            "enable_gpu": False,
            "enable_tpu": False,
            "enable_internet": True,
            "dataset_sources": [],
            "competition_sources": [],
            "kernel_sources": [],
        }
        (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
        print(f"built {d}")


if __name__ == "__main__":
    main()
