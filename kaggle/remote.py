"""Run a script from this repository on a Kaggle kernel and fetch its output.

The repository code (src/, scripts/, kaggle/) and the given script are embedded in a
self-contained kernel; MuJoCo is pip-installed and the hand models are fetched in the
kernel. The command waits for the kernel to finish, downloads its output files to
outputs/kaggle/<slug>/ and prints the script's stdout/stderr.

    uv run python kaggle/remote.py --slug rh-dev path/to/job.py -- --some-arg 1
    uv run python kaggle/remote.py --slug rh-train --gpu train.py      # GPU (T4) kernel
    uv run python kaggle/remote.py --slug rh-dev --no-wait job.py      # push only

Files the job writes under the repository's outputs/ are returned as kernel outputs.
From Git Bash, do not pass absolute POSIX paths as job arguments: MSYS rewrites them
(e.g. /kaggle/working -> C:/Program Files/Git/kaggle/working).
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import os
import shutil
import subprocess
import sys
import time
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
KERNELS = REPO / "outputs" / "kaggle_kernels"
RESULTS = REPO / "outputs" / "kaggle"
MUJOCO_VERSION = "3.15.0"

RUNNER = '''"""Generated by kaggle/remote.py -- do not edit by hand."""
import base64, io, os, shutil, subprocess, sys, zipfile

CODE = "{code}"
ARGS = {args}
PIP = {pip}
ROOT = "/kaggle/working/repo"

zipfile.ZipFile(io.BytesIO(base64.b64decode(CODE))).extractall(ROOT)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", *PIP], check=True)
env = dict(os.environ, PYTHONPATH=f"{{ROOT}}/src:{{ROOT}}/scripts", MUJOCO_GL="egl", PYOPENGL_PLATFORM="egl")
print("cpu_count", os.cpu_count(), flush=True)
subprocess.run([sys.executable, f"{{ROOT}}/scripts/fetch_models.py"], check=True, env=env)
os.chdir("/kaggle/working")
code = subprocess.run([sys.executable, f"{{ROOT}}/_job.py", *ARGS], env=env).returncode
# Files the job wrote to the repository's outputs/ become kernel outputs.
if os.path.isdir(f"{{ROOT}}/outputs"):
    shutil.copytree(f"{{ROOT}}/outputs", "/kaggle/working", dirs_exist_ok=True)
shutil.rmtree(ROOT)  # keep the kernel output to the job's own files
sys.exit(code)
'''


def code_zip(job: Path) -> str:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for folder in ("src", "scripts", "kaggle"):
            for path in (REPO / folder).rglob("*.py"):
                z.write(path, path.relative_to(REPO).as_posix())
        z.write(job, "_job.py")
    return base64.b64encode(buf.getvalue()).decode()


def kaggle(*args: str) -> str:
    # The Kaggle CLI lives in another Python install: do not hand it this venv's interpreter.
    env = {k: v for k, v in os.environ.items() if k not in ("VIRTUAL_ENV", "PYTHONHOME", "PYTHONPATH")}
    venv = os.environ.get("VIRTUAL_ENV", "")
    if venv:
        env["PATH"] = os.pathsep.join(p for p in env.get("PATH", "").split(os.pathsep) if not p.startswith(venv))
    out = subprocess.run(["kaggle", *args], capture_output=True, text=True, env=env, encoding="utf-8", errors="replace")
    return (out.stdout + out.stderr).strip()


def print_log(log: Path) -> None:
    """Kaggle logs are JSON records {stream_name, time, data}, one per line; print the text."""
    for line in log.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip().lstrip("[,").rstrip("]")
        if not line:
            continue
        try:
            sys.stdout.write(json.loads(line).get("data", ""))
        except json.JSONDecodeError:
            sys.stdout.write(line + "\n")


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser()
    ap.add_argument("--slug", required=True)
    ap.add_argument("--user", default="nozomisuzuki")
    ap.add_argument("--gpu", action="store_true")
    ap.add_argument("--source", nargs="*", default=[], help="kernels whose outputs are attached as input")
    ap.add_argument("--pip", nargs="*", default=[], help="extra pip packages")
    ap.add_argument("--no-wait", action="store_true")
    ap.add_argument("--fetch", action="store_true", help="do not push; wait for and fetch the last version")
    ap.add_argument("--timeout", type=float, default=3600, help="give up waiting after this many seconds")
    ap.add_argument("job", type=Path)
    ap.add_argument("args", nargs=argparse.REMAINDER)
    a = ap.parse_args()
    job_args = a.args[1:] if a.args[:1] == ["--"] else a.args

    if not a.fetch:
        push(a, job_args)
    if a.no_wait:
        return
    wait_and_fetch(a)


def push(a: argparse.Namespace, job_args: list[str]) -> None:
    d = KERNELS / a.slug
    d.mkdir(parents=True, exist_ok=True)
    pip = [f"mujoco=={MUJOCO_VERSION}", *a.pip]
    (d / "run.py").write_text(
        RUNNER.format(code=code_zip(a.job), args=repr(job_args), pip=repr(pip)), encoding="utf-8"
    )
    meta = {
        "id": f"{a.user}/{a.slug}",
        "title": a.slug,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": a.gpu,
        "enable_tpu": False,
        "enable_internet": True,
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [s if "/" in s else f"{a.user}/{s}" for s in a.source],
    }
    (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    for attempt in range(5):  # pushes fail transiently (and when 5 CPU sessions are running)
        out = kaggle("kernels", "push", "-p", str(d))
        print(out.splitlines()[-1] if out else "(no output)", flush=True)
        if "successfully pushed" in out:
            return
        time.sleep(30)
    sys.exit("push failed")


def wait_and_fetch(a: argparse.Namespace) -> None:
    t0 = time.time()
    status = ""
    while time.time() - t0 < a.timeout:
        time.sleep(15)
        status = kaggle("kernels", "status", f"{a.user}/{a.slug}")
        if any(s in status for s in ("COMPLETE", "ERROR", "CANCEL")):
            break
    else:
        sys.exit(f"timed out after {a.timeout:.0f}s; last status: {status}")
    print(f"--- {status.split('status')[-1].strip()} after {time.time() - t0:.0f}s", flush=True)
    out = RESULTS / a.slug
    shutil.rmtree(out, ignore_errors=True)  # drop files from earlier versions
    out.mkdir(parents=True)
    kaggle("kernels", "output", f"{a.user}/{a.slug}", "-p", str(out))
    for log in out.glob("*.log"):
        print_log(log)
    print(f"--- outputs in {out}: {sorted(p.name for p in out.iterdir())}")


if __name__ == "__main__":
    main()
